-- One migration, two engines. Every type in it is standard SQL: identity
-- columns for the keys, boolean, varchar. No H2-only limits, no
-- MODE=PostgreSQL compatibility setting, so the PostgreSQL run takes the
-- script unchanged - the same words the H2 run heard.
create table title (
    id     bigint generated by default as identity primary key,
    name   varchar(200) not null,
    author varchar(200) not null,
    isbn   varchar(17) not null unique
);

-- A Copy is an item of exactly one Title.
create table copy (
    id       bigint generated by default as identity primary key,
    title_id bigint not null,
    barcode  varchar(50) not null unique,
    on_loan  boolean not null default false,
    foreign key (title_id) references title (id)
);
