-- The loan table the M08 lab adds, beside the M05 migration that shaped
-- title and copy. Every type again standard SQL: an identity key, two
-- varchars, two dates, no engine-specific syntax, so H2 and PostgreSQL run
-- the script unchanged.

-- A Loan is an active borrowing of exactly one Copy. The columns carry the
-- glossary's vocabulary - member_id and copy_id - never "book id" or
-- "checkout"; the dates are the Loan period's borrowed-on and due-on.
--
-- One Loan per Copy is deliberately NOT declared here: the rule's guard is
-- the borrowing use case's one statement (update copy set on_loan = true
-- where id = :copyId and on_loan = false), whose where clause is the whole
-- condition, reached inside the same transaction that inserts the row. A
-- unique constraint on copy_id would switch the refusal the loser of the
-- race hears from the use case's own words to a constraint violation.
create table loan (
    id          bigint generated by default as identity primary key,
    member_id   varchar(50) not null,
    copy_id     bigint not null,
    borrowed_on date not null,
    due_on      date not null,
    foreign key (copy_id) references copy (id)
);
